package com.smart.report.pdf;

/**
 * جزء من جسم المستند (فقرة، جدول، بيانات، خانات توقيع، رمز...) متقاس على عرض الصفحة، ومستني مكانه.
 *
 * <p>الجزء بيقول عن نفسه بس: إيه اللي بيرسمه ({@link #pieces()}، كل قطعة بطولها وهل تتقسم وفين)، والمسافة
 * حواليه، والمكان اللي محتاجه قبل ما يبدأ. قواعد الصفحات كلها في {@link PageWriter}، مكتوبة مرة واحدة على
 * العقد ده: صفحة جديدة لما القطعة ما تكفيهاش الباقي، تقسيم القطعة الأطول من صفحة، رأس الجدول في أول كل صفحة،
 * الترويسة وتذييل الصفحات ومكانهم، خانات التوقيع مع اللي بيتوقّع عليه، الإيصال الحراري، والفاصل. جزء جديد
 * بيكتب {@link #pieces()} وقطعه، ومن غير ما يلمس قاعدة صفحات واحدة بيتنقل ويتقسم زي الباقي.</p>
 */
interface Part {

    /** المسافة فوق الجزء. بتتشال في أعلى الورقة نفسها، وفي أول مجموعة اتنقلت لصفحة جديدة. */
    default float gapBefore() {
        return 0;
    }

    /** المكان اللي الجزء بيتأكد منه قبل أول قطعة؛ {@link Keep#NONE} = ولا حاجة. */
    default Keep keep() {
        return Keep.NONE;
    }

    /** قطعة بتترسم فوق قطع الجزء في أول كل صفحة بيكمل عليها (رأس الجدول)؛ {@code null} = مفيش. */
    default Piece header() {
        return null;
    }

    /** اللي الجزء بيرسمه من فوق لتحت. جزء ما بيرسمش حاجة (مسافة، نص فاضي) ما لوش قطع. */
    Pieces pieces();

    /** المسافة تحت الجزء، بتفضل في أي مكان. */
    default float gapAfter() {
        return 0;
    }

    /** دور الجزء في مجموعة خانات التوقيع. */
    default Join join() {
        return Join.NONE;
    }

    /** الجزء بيبدأ في صفحة جديدة: فاصل الصفحات. */
    default boolean startsPage() {
        return false;
    }
}
