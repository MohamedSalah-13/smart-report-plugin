package com.smart.report.pdf;

/**
 * خانات التوقيع ما بتنزلش لوحدها في صفحة من غير الأرقام اللي بيتوقّع عليها: الأجزاء اللي قبلها بتتنقل
 * معاها. الدور بيقول الجزء بيتنقل ولا لأ، ولحد فين المجموعة بتوصل.
 */
enum Join {
    /** المجموعة بتقف قبله: الجدول والعنوان وغيرهم بيفضلوا مكانهم. */
    NONE,
    /**
     * بيتنقل مع المجموعة، والمجموعة بتكمل لفوق بعده: النص (التفقيط). آخر سطر فيه بيحجز مكان الجزء اللي
     * بيشد اللي قبله لو بعده على طول (أو بعد مسافات بس).
     */
    THROUGH,
    /** مسافة بين الأجزاء: بتتنقل مع المجموعة وبتعدّيها لفوق، بس المجموعة ما بتبدأش بيها. */
    GAP,
    /** بيتنقل مع المجموعة وهو أولها: الملخص اللي فيه الأرقام. */
    LEAD,
    /** آخر المجموعة، واللي بيشد اللي قبله: خانات التوقيع. */
    ANCHOR
}
